STANDINS = ['music/%s.adp' % k for k in music.TRACKS] + ['sfx/%s.adp' % k for k in SFX]


class Lcg:
    """The integer generator behind every random choice (NumPy's own generators are not promised stable)."""
    def __init__(self, seed):
        self.s = (seed * 2654435761 + 12345) & 0xFFFFFFFF

    def next(self):
        self.s = (self.s * 1664525 + 1013904223) & 0xFFFFFFFF
        return self.s >> 8

    def below(self, n):
        return self.next() % n

    def noise(self, n):
        s = np.empty(n, dtype=np.uint64)
        cur = self.s
        for i in range(n):
            cur = (cur * 1664525 + 1013904223) & 0xFFFFFFFF
            s[i] = cur
        self.s = cur
        return (s >> np.uint64(8)).astype(np.float64) / 8388608.0 - 1.0


def seed_of(name):
    return zlib.crc32(name.encode()) & 0xFFFFFFFF


def to_i16(x, peak):
    m = float(np.max(np.abs(x))) or 1.0
    return np.round(x * (peak / m)).astype(np.int64).tolist()


def env_ad(n, attack, rate):
    t = np.arange(n) / float(rate)
    return np.minimum(1.0, t / max(attack, 1e-4)) * np.exp(-t * (5.0 / max(n / float(rate), 1e-3)))


def tone(freqs, rate, shape='sine'):
    ph = 2.0 * np.pi * np.cumsum(freqs) / rate
    if shape == 'square':
        return np.sign(np.sin(ph)) * 0.6
    if shape == 'tri':
        return 2.0 / np.pi * np.arcsin(np.sin(ph))
    return np.sin(ph)


def lowpass(x, k):
    """A one-pole low pass with a per-sample coefficient array (or a scalar)."""
    k = np.broadcast_to(k, x.shape)
    y = np.empty_like(x)
    acc = 0.0
    for i in range(len(x)):
        acc += k[i] * (x[i] - acc)
        y[i] = acc
    return y


def make_sfx(name):
    kind, secs, f0, f1, rate, _ = SFX[name]
    n = int(secs * rate) & ~1
    rng = Lcg(seed_of(name))
    t = np.arange(n) / float(rate)
    sweep = f0 * (f1 / float(f0)) ** (t / secs)
    if kind == 'blip':
        x = tone(sweep, rate, 'square') * env_ad(n, 0.002, rate)
    elif kind == 'blip2':
        half = n // 2
        f = np.concatenate([np.full(half, float(f0)), np.full(n - half, float(f1))])
        x = tone(f, rate, 'tri') * env_ad(n, 0.002, rate)
    elif kind == 'buzz':
        x = tone(sweep, rate, 'square') * (0.6 + 0.4 * np.sign(np.sin(2 * np.pi * 30 * t))) * env_ad(n, 0.005, rate)
    elif kind == 'tick':
        x = (np.sin(2 * np.pi * f0 * t) + .3 * np.sin(2 * np.pi * 2 * f0 * t)) * np.exp(-t * 140.0)
    elif kind == 'ding':                       # two bell-like notes, each with an instant attack
        half = n // 2
        f = np.concatenate([np.full(half, float(f0)), np.full(n - half, float(f1))])
        tt = np.concatenate([t[:half], t[half:] - t[half]])
        x = (np.sin(2 * np.pi * f * tt) + .35 * np.sin(2 * np.pi * 2 * f * tt) + .12 * np.sin(2 * np.pi * 3 * f * tt)) * np.exp(-tt * 22.0)
    elif kind == 'whoosh':                     # band-limited air: rises and falls, no pitch of its own
        nz = rng.noise(n)
        lo = lowpass(nz, np.clip(2.0 * np.pi * sweep / rate, 0.01, 0.9))
        x = (lo - lowpass(lo, np.clip(2.0 * np.pi * sweep * 0.35 / rate, 0.005, 0.5))) * np.sin(np.pi * (t / secs) ** 0.7) ** 2
    elif kind == 'clack':                      # two short damped knocks and a little body
        x = (np.sin(2 * np.pi * f0 * t) * np.exp(-t * 55.0) + .6 * np.sin(2 * np.pi * f1 * t) * np.exp(-t * 80.0)
             + .8 * np.sin(2 * np.pi * 140.0 * t) * np.exp(-t * 30.0) + .5 * lowpass(rng.noise(n), 0.5) * np.exp(-t * 160.0))
    elif kind == 'thud':
        x = np.sin(2 * np.pi * np.cumsum(sweep) / rate) * np.exp(-t * 16.0) + .4 * lowpass(rng.noise(n), 0.12) * np.exp(-t * 40.0)
    elif kind == 'encounter':
        up = t / secs
        nz = lowpass(rng.noise(n), np.clip(2.0 * np.pi * sweep / rate, 0.01, 0.9))
        x = nz * np.clip(up / 0.75, 0, 1) ** 2 * (up < 0.78) + 1.4 * np.sin(2 * np.pi * np.cumsum(60.0 + 80.0 * np.exp(-(t - 0.78 * secs).clip(0) * 25.0)) / rate) * np.exp(-(t - 0.78 * secs).clip(0) * 9.0) * (up >= 0.78)
    elif kind == 'noise':
        x = lowpass(rng.noise(n), np.clip(2.0 * np.pi * sweep / rate, 0.01, 0.9)) * np.sin(np.pi * t / secs) ** 0.7
    elif kind == 'crack':
        x = (rng.noise(n) * np.exp(-t * 40.0) + 0.7 * tone(sweep, rate, 'tri') * np.exp(-t * 14.0))
    elif kind == 'clank':
        x = sum(tone(np.full(n, f0 * m), rate) * np.exp(-t * (14.0 + 8.0 * i)) / (1.0 + i) for i, m in enumerate((1.0, 2.52, 4.21)))
        x = x + 0.3 * lowpass(rng.noise(n), 0.4) * np.exp(-t * 90.0)
    elif kind == 'boom':
        x = tone(sweep, rate) * np.exp(-t * (3.5 / secs)) + 0.5 * lowpass(rng.noise(n), 0.08) * np.exp(-t * 8.0)
    elif kind == 'zap':
        x = tone(sweep * (1.0 + 0.3 * np.sin(2 * np.pi * 45 * t)), rate, 'square') * env_ad(n, 0.003, rate)
    elif kind == 'rise':
        x = (tone(sweep, rate, 'tri') + 0.5 * tone(sweep * 1.5, rate)) * (t / secs) ** 1.5 * np.minimum(1.0, (secs - t) * 20.0)
    elif kind == 'rattle':
        gate = (np.sin(2 * np.pi * (9.0 + 6.0 * t / secs) * t) > 0.3).astype(np.float64)
        x = lowpass(rng.noise(n), np.clip(2.0 * np.pi * sweep / rate, 0.01, 0.9)) * gate * np.exp(-t * (2.0 / secs))
    elif kind == 'chime':
        x = (tone(np.full(n, float(f0)), rate) + 0.6 * tone(np.full(n, float(f1)), rate) * (t > secs * 0.18)) * np.exp(-t * (4.0 / secs))
    elif kind == 'crowd':
        x = lowpass(rng.noise(n), 0.25) * (0.6 + 0.4 * np.sin(2 * np.pi * 3.1 * t) * np.sin(2 * np.pi * 0.7 * t)) * np.sin(np.pi * t / secs) ** 0.5
    else:
        raise ValueError(kind)
    edge = min(n // 4, int(0.004 * rate))
    head = 8 if kind in ('tick', 'ding', 'clack', 'thud') else edge       # a click-free but immediate attack
    x[:head] *= np.linspace(0.0, 1.0, head)
    x[-edge:] *= np.linspace(1.0, 0.0, edge)
    pcm = to_i16(x, 26000)
    data, info = adpcm.encode(pcm)
    return adpcm.pack(data, rate, info['samples'], info['loop_start'], info['loop_end'])


def make_music(name):
    builder, loop = music.TRACKS[name]
    y = builder().render(loop)
    pcm = np.round(y * 32767.0).astype(np.int64).tolist()
    if loop:
        data, info = adpcm.encode(pcm, 0, len(pcm))
    else:
        data, info = adpcm.encode(pcm)
    return adpcm.pack(data, synth.R, info['samples'], info['loop_start'], info['loop_end'])


def build(rel):
    kind, name = rel.split('/')
    name = name[:-4]
    return make_music(name) if kind == 'music' else make_sfx(name)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=os.path.join(ROOT, 'romdisk', 'audio'))
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--only', default='')
    ap.add_argument('--wav', default='')
    args = ap.parse_args()
    bad = 0
    total = {'music': 0, 'sfx': 0}
    for rel in STANDINS:
        if args.only and args.only not in rel:
            continue
        blob = build(rel)
        path = os.path.join(args.out, rel)
        total[rel.split('/')[0]] += len(blob)
        if args.wav:
            import struct
            import wave
            info, pcm, _, _ = adpcm.decode_adp(blob)
            os.makedirs(args.wav, exist_ok=True)
            with wave.open(os.path.join(args.wav, rel.replace('/', '_')[:-4] + '.wav'), 'wb') as w:
                w.setnchannels(1)
                w.setsampwidth(2)
                w.setframerate(info['rate'])
                w.writeframes(struct.pack('<%dh' % len(pcm), *pcm))
        if args.check:
            if not os.path.exists(path) or open(path, 'rb').read() != blob:
                print('DIFFERS %s' % rel)
                bad += 1
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, 'wb') as f:
                f.write(blob)
    print('%s %d sounds: music %.1f KiB, sfx %.1f KiB%s' % ('checked' if args.check else 'wrote', len(STANDINS),
          total['music'] / 1024.0, total['sfx'] / 1024.0, ', %d differ' % bad if bad else ''))
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
