"""make_standins.py - builds every sound on the romdisk (slice 3D-7, docs/NEXT_SLICE_SOUND_SAVE.md 7.3). Seeded and
byte-reproducible; Python 3 + NumPy.

    python3 tools/audio/make_standins.py            # writes romdisk/audio/{music,sfx}/*.adp
    python3 tools/audio/make_standins.py --check    # exit 1 if a committed file differs from what this generates
    python3 tools/audio/make_standins.py --out DIR  # somewhere else (tests)
    python3 tools/audio/make_standins.py --wav DIR  # also a .wav of each sound as the console decodes it (to listen)

Music: the soundtrack written in music.py (synth.py), 22,050 Hz mono, looped tracks with reset seams (adpcm.py).
Effects: procedural, from the small synth below - placeholders until recorded sounds replace them through
make_audio.py (not written yet: Stage B4). STANDINS is the list the licence check reads: a file listed here is
generated by this repository and needs no SOURCES.md entry.
"""
